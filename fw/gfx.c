int text(int x, int y, const char *s, int scale) {
    for (; *s; s++, x += 6 * scale) {
        int c = *s >= 'a' && *s <= 'z' ? *s - 32 : *s;
        if (c < 0x20 || c > 0x5F) c = '?';
        for (int col = 0; col < 5; col++)
            for (int row = 0; row < 7; row++)
                if (font5x7[c - 0x20][col] >> row & 1) rect(x + col * scale, y + row * scale, scale, scale);
    }
    return x;
}

